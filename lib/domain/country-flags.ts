const normalizeTeamName = (teamName: string): string =>
  teamName
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s*&\s*/g, " and ")
    .toLowerCase()
    .trim();

export const getTeamFlag = (teamName: string): string => {
  const normalized = normalizeTeamName(teamName);

  const override = flagOverrideByTeamName[normalized];
  if (override) {
    return override;
  }

  const isoCode = isoCodeByTeamName[normalized];
  return isoCode ? isoToFlagEmoji(isoCode) : "\u{1F3F3}\u{FE0F}";
};
