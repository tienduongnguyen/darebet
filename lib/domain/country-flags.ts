const REGIONAL_INDICATOR_OFFSET = 0x1f1e6 - "A".charCodeAt(0);

const isoToFlagEmoji = (isoCode: string): string =>
  String.fromCodePoint(
    ...[...isoCode.toUpperCase()].map(
      (char) => char.charCodeAt(0) + REGIONAL_INDICATOR_OFFSET,
    ),
  );

